"""The inventory page: every pattern and use case with a link and a summary, then the
candidates, then what needs attention. Rendered as Markdown, standalone HTML or JSON.

The output carries no date, so regenerating an unchanged portfolio changes nothing.
"""
from __future__ import annotations

import html
import json
import os

from .docs import LABELS, PRIORITIES, TYPES, truthy

ORDER = {p: i for i, p in enumerate(PRIORITIES)}
SINGULAR = {"architecture-pattern": "Architecture pattern", "reference-architecture": "Reference architecture",
            "collaboration": "Collaboration", "use-case": "Use case"}
ATTENTION = ("needs-conversion", "proposed-deprecation", "archive")


def _key(d):
    pr = str(d.portfolio.get("priority") or "").lower()
    return (ORDER.get(pr, len(ORDER)), d.id or "~", d.title.lower())


def build(docs, out_path=None, link_base="", include_archived=False) -> dict:
    """The inventory as plain data: groups of rows, and counts."""
    out_dir = os.path.dirname(os.path.abspath(out_path)) if out_path else None

    def link(d):
        if link_base and d.id and not d.is_candidate:
            # The cross-reference skill's stable address, which survives a page moving.
            return f"{link_base.rstrip('/')}/id/{d.id}/"
        if out_dir:
            return os.path.relpath(d.path, out_dir).replace(os.sep, "/")
        return d.rel

    def row(d):
        p = d.portfolio
        return {
            "id": d.id, "title": d.title, "type": d.type or "unknown", "status": d.status,
            "state": d.state, "priority": str(p.get("priority") or ""),
            "target_quarter": str(p.get("target_quarter") or ""),
            "committed": truthy(p.get("committed")) if "committed" in p else None,
            "summary": d.summary, "path": d.rel, "link": link(d),
            "reason": str(p.get("reason") or ""), "legacy": d.legacy,
            "archived_from": str(p.get("archived_from") or ""),
            "candidate_type": str(d.fm.get("candidate_type") or "") if d.is_candidate else "",
        }

    live = [d for d in docs if not d.archived and d.state != "archived" and d.kind]
    groups = []
    for t in TYPES + ("",):
        rows = [row(d) for d in sorted((d for d in live if not d.is_candidate and d.type == t), key=_key)]
        if rows:
            groups.append({"type": t or "unknown", "label": LABELS.get(t, "Type not declared"), "rows": rows})
    candidates = [row(d) for d in sorted((d for d in live if d.is_candidate), key=_key)]
    attention = [row(d) for d in sorted((d for d in live if d.state in ATTENTION), key=lambda d: (d.state, _key(d)))]
    archived = [row(d) for d in sorted((d for d in docs if d.archived or d.state == "archived"), key=_key)] \
        if include_archived else []
    problems = [{"path": d.rel, "problems": d.problems + (["legacy signature: run portfolio.py sign"] if d.legacy else [])}
                for d in docs if d.problems or d.legacy]
    counts = {g["type"]: len(g["rows"]) for g in groups}
    counts["candidate"] = len(candidates)
    for s in ("placeholder", "draft") + ATTENTION:
        counts[s] = sum(1 for d in live if d.state == s)
    counts["committed"] = sum(1 for d in live if truthy(d.portfolio.get("committed")))
    counts["archived"] = sum(1 for d in docs if d.archived or d.state == "archived")
    return {"groups": groups, "candidates": candidates, "attention": attention,
            "archived": archived, "problems": problems, "counts": counts}


# ------------------------------------------------------------------ Markdown

def _cell(s) -> str:
    return str(s if s is not None else "").replace("|", "\\|").replace("\n", " ")


def _committed(v) -> str:
    return "" if v is None else ("yes" if v else "no")


def markdown(inv: dict, title="Pattern portfolio") -> str:
    c = inv["counts"]
    out = ["---", f"title: {title}",
           "description: Every architecture pattern, reference architecture, collaboration and use case in the repository, with the candidates and what needs attention.",
           "---", "",
           "<!-- Generated by the portfolio skill: portfolio.py inventory. Do not edit; regenerate. -->", "",
           f"# {title}", ""]
    total = sum(len(g["rows"]) for g in inv["groups"])
    parts = [f"{len(g['rows'])} {(g['label'] if len(g['rows']) != 1 else SINGULAR.get(g['type'], g['label'])).lower()}"
             for g in inv["groups"]]
    out.append(f"{total} documents: {', '.join(parts) or 'none'}. {c['candidate']} candidates, "
               f"{c['committed']} committed, {c['placeholder']} placeholders awaiting a draft, "
               f"{c['draft']} drafts awaiting review.")
    out.append("")
    head = "| ID | Title | Status | State | Priority | Quarter | Committed | Summary |"
    sep = "|---|---|---|---|---|---|---|---|"
    for g in inv["groups"]:
        out += [f"## {g['label']}", "", head, sep]
        for r in g["rows"]:
            out.append(f"| {_cell(r['id'])} | [{_cell(r['title'])}]({r['link']}) | {_cell(r['status'])} | {_cell(r['state'])} "
                       f"| {_cell(r['priority'])} | {_cell(r['target_quarter'])} | {_committed(r['committed'])} | {_cell(r['summary'])} |")
        out.append("")
    out += ["## Candidates", ""]
    if inv["candidates"]:
        out += ["Possible patterns, noted but not formally patterns yet.", "",
                "| Candidate | Type | Priority | Quarter | Committed | Summary |", "|---|---|---|---|---|---|"]
        for r in inv["candidates"]:
            out.append(f"| [{_cell(r['title'])}]({r['link']}) | {_cell(r['candidate_type'])} | {_cell(r['priority'])} "
                       f"| {_cell(r['target_quarter'])} | {_committed(r['committed'])} | {_cell(r['summary'])} |")
    else:
        out.append("None.")
    out += ["", "## Needs attention", ""]
    if inv["attention"]:
        out += ["| State | ID | Title | Reason |", "|---|---|---|---|"]
        for r in inv["attention"]:
            out.append(f"| {r['state']} | {_cell(r['id'])} | [{_cell(r['title'])}]({r['link']}) | {_cell(r['reason'])} |")
    else:
        out.append("Nothing needs conversion, deprecation or archiving.")
    if inv["archived"]:
        out += ["", "## Archived", "", "| ID | Title | Archived from |", "|---|---|---|"]
        for r in inv["archived"]:
            out.append(f"| {_cell(r['id'])} | [{_cell(r['title'])}]({r['link']}) | {_cell(r['archived_from'])} |")
    if inv["problems"]:
        out += ["", "## Signature problems", ""]
        for p in inv["problems"]:
            out.append(f"- `{p['path']}`: {'; '.join(p['problems'])}")
    return "\n".join(out).rstrip() + "\n"


# ------------------------------------------------------------------ HTML

CSS = """
:root{--bg:#fff;--fg:#1d1d1f;--muted:#5f6368;--line:#dadce0;--head:#f4f5f7;--accent:#1a56db}
@media (prefers-color-scheme: dark){:root{--bg:#121212;--fg:#e8eaed;--muted:#9aa0a6;--line:#3c4043;--head:#1e1f21;--accent:#8ab4f8}}
body{background:var(--bg);color:var(--fg);font:15px/1.5 system-ui,sans-serif;margin:0;padding:24px 16px}
main{max-width:1200px;margin:0 auto}h1{font-size:1.7rem}h2{font-size:1.2rem;margin-top:2rem}
.lead{color:var(--muted)}.wrap{overflow-x:auto}table{border-collapse:collapse;width:100%;font-size:.9rem}
th,td{border-bottom:1px solid var(--line);padding:6px 8px;text-align:left;vertical-align:top}
th{background:var(--head)}a{color:var(--accent)}code{font-size:.85em}
"""


def _h(s) -> str:
    return html.escape(str(s if s is not None else ""))


def _table(headers, rows) -> str:
    th = "".join(f"<th>{_h(h)}</th>" for h in headers)
    body = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return f'<div class="wrap"><table><thead><tr>{th}</tr></thead><tbody>{body}</tbody></table></div>'


def to_html(inv: dict, title="Pattern portfolio") -> str:
    a = lambda r: f'<a href="{_h(r["link"])}">{_h(r["title"])}</a>'  # noqa: E731
    parts = [f"<h1>{_h(title)}</h1>"]
    c = inv["counts"]
    total = sum(len(g["rows"]) for g in inv["groups"])
    parts.append(f'<p class="lead">{total} documents, {c["candidate"]} candidates, {c["committed"]} committed, '
                 f'{c["placeholder"]} placeholders, {c["draft"]} drafts awaiting review.</p>')
    for g in inv["groups"]:
        parts.append(f"<h2>{_h(g['label'])}</h2>")
        parts.append(_table(["ID", "Title", "Status", "State", "Priority", "Quarter", "Committed", "Summary"],
                            [[_h(r["id"]), a(r), _h(r["status"]), _h(r["state"]), _h(r["priority"]),
                              _h(r["target_quarter"]), _committed(r["committed"]), _h(r["summary"])] for r in g["rows"]]))
    parts.append("<h2>Candidates</h2>")
    parts.append(_table(["Candidate", "Type", "Priority", "Quarter", "Committed", "Summary"],
                        [[a(r), _h(r["candidate_type"]), _h(r["priority"]), _h(r["target_quarter"]),
                          _committed(r["committed"]), _h(r["summary"])] for r in inv["candidates"]])
                 if inv["candidates"] else "<p>None.</p>")
    parts.append("<h2>Needs attention</h2>")
    parts.append(_table(["State", "ID", "Title", "Reason"],
                        [[_h(r["state"]), _h(r["id"]), a(r), _h(r["reason"])] for r in inv["attention"]])
                 if inv["attention"] else "<p>Nothing needs conversion, deprecation or archiving.</p>")
    if inv["archived"]:
        parts.append("<h2>Archived</h2>")
        parts.append(_table(["ID", "Title"], [[_h(r["id"]), a(r)] for r in inv["archived"]]))
    if inv["problems"]:
        parts.append("<h2>Signature problems</h2><ul>" + "".join(
            f"<li><code>{_h(p['path'])}</code>: {_h('; '.join(p['problems']))}</li>" for p in inv["problems"]) + "</ul>")
    return ("<!doctype html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">"
            "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">"
            f"<title>{_h(title)}</title><style>{CSS}</style></head>\n"
            "<!-- Generated by the portfolio skill: portfolio.py inventory. Do not edit; regenerate. -->\n"
            f"<body><main>{''.join(parts)}</main></body></html>\n")


def render(inv: dict, fmt: str, title="Pattern portfolio") -> str:
    if fmt == "json":
        return json.dumps(inv, indent=2, ensure_ascii=False) + "\n"
    if fmt == "html":
        return to_html(inv, title)
    return markdown(inv, title)
